import { z } from "zod";
import * as C from "./contract";

const props = (schema: z.ZodType) =>
	(z.toJSONSchema(schema, { unrepresentable: "any", io: "input" }) as {
		properties: Record<string, { maxLength?: number; maximum?: number; maxItems?: number }>;
	}).properties;

const track = props(C.CreateTrackRequest);
const login = props(C.LoginRequest);
const playlist = props(C.CreatePlaylistRequest);

const limits: [string, number | undefined][] = [
	["MaxAudioBase64", C.MAX_AUDIO_BASE64],
	["MaxImageBase64", C.MAX_IMAGE_BASE64],
	["MaxNameLength", track.title?.maxLength],
	["MaxDurationMs", track.duration?.maximum],
	["MaxArtistsPerTrack", track.artistIds?.maxItems],
	["MaxUsernameLength", login.username?.maxLength],
	["MaxPasswordLength", login.password?.maxLength],
	["MaxTracksPerPlaylist", playlist.trackIds?.maxItems],
];
for (const [name, value] of limits) {
	if (!Number.isInteger(value)) throw new Error(`${name}: no bound found in the contract`);
}

const screaming = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
const header = "Code generated by contract/gen-limits.ts. DO NOT EDIT.";
const root = `${import.meta.dir}/..`;

await Bun.write(
	`${root}/internal/backend/limits_gen.go`,
	`// ${header}\n\npackage backend\n\n${limits.map(([n, v]) => `const ${n} = ${v}\n`).join("")}`,
);
await Bun.write(
	`${root}/frontend/src/lib/limits.gen.ts`,
	`// ${header}\n\n${limits.map(([n, v]) => `export const ${screaming(n)} = ${v};\n`).join("")}`,
);
